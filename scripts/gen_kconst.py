"""Per-scene KernelData constant header for -DCYCLES_KDATA_CONST (configs/<scene>/kdata_const.h).
gen_kconst.py <out.h> <table.tsv> <dump.log>...   (dumps of a CYCLES_KDATA_DUMP cubin: KDF field table, KDW words)
A data_template.h field is folded when it has one value over every upload in every dump (here: the benchmark run and
the 4096-spp check render); float4/float2 members stay runtime. table.tsv lists every field: parent, name, type,
folded or runtime, the values seen."""
import re, struct, sys
from collections import OrderedDict
out, table, dumps = sys.argv[1], sys.argv[2], sys.argv[3:]
fields = OrderedDict()   # (parent, name) -> (type, offset, size)
seen = {}                # (parent, name) -> set of raw word tuples
for d in dumps:
    words = {}
    for line in open(d, errors="replace"):
        m = re.search(r"KDF (\w+) (\w+) (\w+) (\d+) (\d+)", line)
        if m:
            fields[(m[1], m[3])] = (m[2], int(m[4]), int(m[5]))
            continue
        m = re.search(r"KDW (\d+) (\d+) ([0-9a-f]{8}) ([0-9a-f]{8}) ([0-9a-f]{8}) ([0-9a-f]{8})", line)
        if m:
            c, i = int(m[1]), int(m[2])
            for k in range(4):
                words.setdefault(c, {})[i + k] = int(m[3 + k], 16)
    assert words, f"no KDW lines in {d}"
    for c, w in words.items():
        for key, (t, off, size) in fields.items():
            seen.setdefault(key, set()).add(tuple(w[off // 4 + k] for k in range(size // 4)))
assert fields, "no KDF lines"
STRUCT = {"background": "KernelBackground", "bvh": "KernelBVH", "film": "KernelFilm", "integrator": "KernelIntegrator",
          "image": "KernelImage", "svm_usage": "KernelSVMUsage",
          "svm_specialization": "KernelSVMSpecialization"}   # the last: trees with SVM specialization (rtx6000 v53-all)
def lit(t, w):
    if t == "float":
        f = struct.unpack("<f", struct.pack("<I", w))[0]
        return f"{f.hex()}f" if f == f and abs(f) != float("inf") else None
    if t in ("int", "uint"):
        v = w - (1 << 32) if (t == "int" and w >= 1 << 31) else w
        return f"{v}" + ("u" if t == "uint" else "")
    return None
body = {p: [] for p in STRUCT}
rows = []
for (p, n), (t, off, size) in fields.items():
    vals = seen[(p, n)]
    v = lit(t, next(iter(vals))[0]) if len(vals) == 1 and size == 4 else None
    shown = " ".join(",".join(f"{x:08x}" for x in vv) for vv in sorted(vals))
    rows.append(f"{p}\t{n}\t{t}\t{'folded' if v is not None else 'runtime'}\t{v if v is not None else shown}")
    if v is not None:
        body[p].append(f"  static constexpr {t} {n} = {v};")
with open(out, "w") as f:
    f.write("/* Generated by scripts/gen_kconst.py from " + " ".join(dumps) + " */\n#pragma once\n")
    for p, s in STRUCT.items():
        f.write(f"struct KDC_{s} : public {s} {{\n" + "\n".join(body[p]) + ("\n" if body[p] else "") + "};\n")
open(table, "w").write("parent\tname\ttype\tstatus\tvalue\n" + "\n".join(rows) + "\n")
print(out, sum(len(b) for b in body.values()), "folded of", len(fields), "; runtime:",
      " ".join(f"{r.split(chr(9))[0]}.{r.split(chr(9))[1]}" for r in rows if "\truntime\t" in r))
